def verify_stocks(stock_codes: List[str], sample_size: int = 5) -> List[str]:
    """
    종목 코드가 유효한지 샘플 확인

    Args:
        stock_codes: 종목 코드 리스트
        sample_size: 테스트할 샘플 개수

    Returns:
        유효한 종목 코드 리스트
    """
    print(f"📊 총 {len(stock_codes)}개 종목")
    print(f"🔍 샘플 {sample_size}개 종목 검증 중...")

    valid_count = 0
    for code in stock_codes[:sample_size]:
        ticker = f"{code}.KS"
        try:
            data = yf.download(ticker, period="5d", progress=False)
            if not data.empty:
                valid_count += 1
                print(f"   ✅ {code}: 데이터 확인됨")
            else:
                print(f"   ⚠️  {code}: 데이터 없음")
        except Exception as e:
            print(f"   ❌ {code}: 오류 - {e}")

    print(f"\n검증 결과: {valid_count}/{sample_size} 성공")
    return stock_codes


def save_stock_list(stock_codes: List[str], filename: str = "kospi_top100.txt"):
    """종목 리스트를 파일로 저장"""
    with open(filename, 'w') as f:
        for code in stock_codes:
            f.write(f"{code}\n")
    print(f"\n💾 종목 리스트 저장: {filename}")


